#!/usr/bin/env python3
"""Regenerate src/main/computer/keymap.js from the kernel header. Run from repo root."""
import re, json
h = open('/usr/include/linux/input-event-codes.h').read()
keys = {m.group(1).lower(): int(m.group(2), 0)
        for m in re.finditer(r'^#define\s+KEY_(\w+)\s+(0x[0-9a-fA-F]+|\d+)\b', h, re.M)}
alias = {'ctrl':'leftctrl','control':'leftctrl','shift':'leftshift','alt':'leftalt','super':'leftmeta',
         'meta':'leftmeta','win':'leftmeta','windows':'leftmeta','cmd':'leftmeta','command':'leftmeta',
         'return':'enter','escape':'esc','del':'delete','pgup':'pageup','pgdn':'pagedown','pgdown':'pagedown',
         'printscreen':'sysrq','prtsc':'sysrq','menu':'compose'}
bad = [v for v in alias.values() if v not in keys]
assert not bad, f'aliases point at missing keys: {bad}'
open('src/main/computer/keymap.js', 'w').write(
    "'use strict';\n// AUTO-GENERATED by scripts/gen-keymap.py - do not edit.\nmodule.exports = "
    + json.dumps({'codes': keys, 'aliases': alias}, indent=1, sort_keys=True) + ";\n")
print(f'wrote keymap.js: {len(keys)} keys')
