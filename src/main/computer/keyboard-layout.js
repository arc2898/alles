'use strict';

const { execFile } = require('node:child_process');
const DATA = require('./keyboard-layout-data');

/**
 * Which keyboard layout is typing right now, and WHICH CHARACTERS can it make? That decides how text and shortcuts are sent
 * through GNOME's remote-input service:
 *
 *   - Text goes by KEYSYM ("the character a"). The service looks the keysym up in the active layout, takes the FIRST key (lowest
 *     keycode) that has it on any level, and presses Shift or AltGr when that level needs one. It cannot press any other level: a
 *     character found there comes out as the bare key ("<" on a British keyboard types "z"). A keysym the layout does not have
 *     types NOTHING (all measured on GNOME Shell 46) - so every character the layout cannot make has to be pasted instead.
 *   - "Cannot make" is not only "a Russian keyboard has no Latin letters". German has no plain ^ or ` (dead keys), plain
 *     "Indian" is Devanagari, "Arabic" has no Latin letters ... The exact answer for every layout xkeyboard-config knows is in
 *     keyboard-layout-data.js (generated by scripts/gen-layout-data.py, which replays the service's choice of key with libxkbcommon).
 *   - A shortcut's letter key goes by keysym when the layout can make that letter (Ctrl+Z is Ctrl+Z on a German keyboard), and by its
 *     place on the keyboard when it cannot (which is what apps match on a Cyrillic layout).
 *   - An input method (ibus: Japanese, Chinese, Korean ...) turns keys into other text, so text is pasted and keys go by place.
 *
 * GNOME keeps the list of layouts and the active one in settings, read here with the `gsettings` tool every GNOME desktop has.
 * If it cannot be read (not GNOME, tool missing) the answer is "a US layout": right for most people, and typing then works as before.
 */

const ALL_ASCII = (() => { let s = ''; for (let c = 0x20; c <= 0x7e; c++) s += String.fromCharCode(c); return s; })();
const LETTERS = ALL_ASCII.replace(/[^A-Za-z]/g, '');

// ONLY for a layout the generated table has no record of (a newer variant, or one that would not compile): the base layouts
// (the part before a "+variant") whose keys make no Latin letters. Err on the side of pasting: that is slower but always right.
const NON_LATIN = new Set([
  'ru', 'ua', 'by', 'bg', 'kz', 'kg', 'mk', 'mn', 'tj', 'rs',            // Cyrillic
  'gr', 'ge', 'am',                                                       // Greek, Georgian, Armenian
  'il', 'ara', 'sy', 'iq', 'ir', 'af', 'pk',                              // Hebrew, Arabic, Syriac, Persian, Pashto/Dari, Urdu
  'th', 'kh', 'la', 'np', 'lk', 'bd', 'et', 'mv', 'bt', 'in',            // Thai, Khmer, Lao, Nepali, Sinhala, Bengali, Ethiopic, Dhivehi, Dzongkha, Indian (Devanagari)
  'brai',                                                                 // Braille
]);

// An unrecorded variant of a non-Latin layout counts as Latin only if its name says so (rs+latin, by+latin, il+lat ...).
const LATIN_VARIANT = /latin|lat\b/i;

const CHILD_ENV_KEYS = ['PATH', 'HOME', 'XDG_RUNTIME_DIR', 'XDG_CONFIG_HOME', 'XDG_DATA_DIRS', 'DBUS_SESSION_BUS_ADDRESS', 'LANG'];

const COMPLETE = new Set(DATA.COMPLETE);
const has = (o, k) => Object.prototype.hasOwnProperty.call(o, k);

/** Can every Latin letter, both cases, be typed? (`missing` = what the layout cannot make.) Says nothing about punctuation. */
const isLatin = (missing) => [...LETTERS].every((c) => !missing.includes(c));

/**
 * The printable ASCII characters a layout cannot make by keysym.
 * @returns {{missing: string, known: boolean}}  known = the answer comes from the generated table, not from a guess at the name
 */
function missingFor(id) {
  if (has(DATA.MISSING, id)) return { missing: DATA.MISSING[id], known: true };
  if (COMPLETE.has(id)) return { missing: '', known: true };
  const [base, variant = ''] = String(id).split('+');
  if (variant) {
    // not recorded: most likely written in the same script as its base layout, unless its name says Latin
    if (LATIN_VARIANT.test(variant)) return { missing: '', known: false };
    return { missing: missingFor(base).missing, known: false };
  }
  return { missing: NON_LATIN.has(base) ? ALL_ASCII : '', known: false };
}

/** [('xkb', 'us'), ('ibus', 'mozc-jp')]  ->  [{type, id}] . Tolerates "@a(ss) []" and anything unexpected (-> []). */
function parseSources(text) {
  const out = [];
  const re = /\(\s*'([^']*)'\s*,\s*'([^']*)'\s*\)/g;
  let m;
  while ((m = re.exec(String(text || ''))) !== null) out.push({ type: m[1], id: m[2] });
  return out;
}

/** "uint32 1" -> 1 ; anything else -> 0.  (The number is the LAST thing on the line: "uint32" has digits of its own.) */
function parseCurrent(text) {
  const m = /(\d+)\s*$/.exec(String(text || ''));
  return m ? Number(m[1]) : 0;
}

/**
 * Turn the list + the active index into what the caller needs to know:
 *   {type, id, base, variant, latin, ime, missing, known}
 *   latin    every Latin letter can be typed (it says nothing about punctuation)
 *   ime      an input method: keys do not make the characters on them
 *   missing  the printable ASCII characters that cannot be typed by keysym (all of them for an input method)
 */
function describeSource(sources, current) {
  const list = sources.length ? sources : [{ type: 'xkb', id: 'us' }];
  const src = list[Math.min(Math.max(Number.isFinite(current) ? current : 0, 0), list.length - 1)];
  if (src.type !== 'xkb') return { type: src.type, id: src.id, base: src.id, variant: '', latin: false, ime: true, missing: ALL_ASCII, known: true };
  const [base, variant = ''] = src.id.split('+');
  const { missing, known } = missingFor(src.id);
  return { type: 'xkb', id: src.id, base, variant, latin: isLatin(missing), ime: false, missing, known };
}

/**
 * Can the layout make this character by keysym? A layout object without `missing` (older code, a test double) is judged by
 * `latin` alone. Anything that is not printable ASCII is never "typeable": it is pasted.
 */
function canType(layout, ch) {
  if (!layout || layout.ime) return false;
  const c = String(ch).codePointAt(0);
  if (!(c >= 0x20 && c <= 0x7e)) return false;
  if (typeof layout.missing === 'string') return !layout.missing.includes(String.fromCharCode(c));
  return layout.latin !== false;
}

const GUESSED = () => ({ type: 'xkb', id: 'us', base: 'us', variant: '', latin: true, ime: false, missing: '', known: false, guessed: true });

/** Read the active layout. Never throws: on any trouble it answers with the default "US layout". */
function readLayout({ exec = execFile, env = process.env, timeoutMs = 2000 } = {}) {
  return new Promise((resolve) => {
    const childEnv = {};
    for (const k of CHILD_ENV_KEYS) if (typeof env[k] === 'string') childEnv[k] = env[k];
    if (!childEnv.PATH) childEnv.PATH = '/usr/local/bin:/usr/bin:/bin';
    let done = false;
    const finish = (v) => { if (!done) { done = true; resolve(v); } };
    try {
      exec('gsettings', ['list-recursively', 'org.gnome.desktop.input-sources'], { env: childEnv, timeout: timeoutMs }, (err, stdout) => {
        if (err) return finish(GUESSED());
        let sources = []; let current = 0;
        for (const line of String(stdout).split('\n')) {
          const m = /^\S+\s+(\S+)\s+(.*)$/.exec(line);
          if (!m) continue;
          if (m[1] === 'sources') sources = parseSources(m[2]);
          else if (m[1] === 'current') current = parseCurrent(m[2]);
        }
        finish(describeSource(sources, current));
      });
    } catch {
      finish(GUESSED());
    }
  });
}

module.exports = { readLayout, parseSources, parseCurrent, describeSource, missingFor, canType, isLatin, NON_LATIN, ALL_ASCII, CHILD_ENV_KEYS };
